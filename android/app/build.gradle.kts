// android/key.properties is gitignored (it's the real release keystore's
// passwords) — release signing just falls back to nulls (Gradle errors out
// at sign time with a clear message) on a checkout that doesn't have it.
val keystoreProperties = Properties()
val keystorePropertiesFile = rootProject.file("key.properties")
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

